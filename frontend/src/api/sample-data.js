const delay = (duration = 400) =>
  new Promise((resolve) => setTimeout(resolve, duration))

const matchesOptionalFilter = (value, filter) => {
  const normalizedFilter = String(filter ?? '').trim()
  return (
    normalizedFilter === '' ||
    normalizedFilter.toLowerCase() === 'all' ||
    String(value).toLowerCase() === normalizedFilter.toLowerCase()
  )
}

export async function getRegistrations({
  participantName = '',
  type = '',
  status = '',
  page = 1,
  pageSize = 10,
} = {}) {
  await delay()

  const searchTerm = String(participantName ?? '').trim().toLowerCase()
  const currentPage = Number.isInteger(page) && page > 0 ? page : 1
  const currentPageSize =
    Number.isInteger(pageSize) && pageSize > 0 ? pageSize : 10
  const filteredRegistrations = sampleRegistrations.filter((registration) => {
    const matchesName = registration.participantName
      .toLowerCase()
      .includes(searchTerm)

    return (
      matchesName &&
      matchesOptionalFilter(registration.registrationType, type) &&
      matchesOptionalFilter(registration.status, status)
    )
  })
  const startIndex = (currentPage - 1) * currentPageSize

  return {
    items: filteredRegistrations.slice(startIndex, startIndex + currentPageSize),
    page: currentPage,
    pageSize: currentPageSize,
    totalCount: filteredRegistrations.length,
    totalPages: Math.ceil(filteredRegistrations.length / currentPageSize),
  }
}

export async function getSummary() {
  await delay()

  return sampleRegistrations.reduce(
    (summary, registration) => {
      summary.totalRegistrations += 1
      summary.totalFees += registration.registrationFee
      summary.totalPayments += registration.amountPaid
      summary.uncollectedPayments +=
        registration.registrationFee - registration.amountPaid
      summary[registration.status === 'CheckedIn' ? 'checkedIn' : registration.status.toLowerCase()] += 1
      return summary
    },
    {
      totalRegistrations: 0,
      confirmed: 0,
      checkedIn: 0,
      pending: 0,
      cancelled: 0,
      totalFees: 0,
      totalPayments: 0,
      uncollectedPayments: 0,
    },
  )
}
