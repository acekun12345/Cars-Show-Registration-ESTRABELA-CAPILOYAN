export async function getRegistrations({
  participantName = '',
  type = '',
  status = '',
  page = 1,
  pageSize = 10,
} = {}) {
  await delay(400)

  const searchTerm = participantName.trim().toLowerCase()
  const filteredItems = sampleRegistrations.filter((registration) => {
    const matchesName =
      !searchTerm || registration.participantName.toLowerCase().includes(searchTerm)
    const matchesType = !type || type === 'All' || registration.registrationType === type
    const matchesStatus = !status || status === 'All' || registration.status === status

    return matchesName && matchesType && matchesStatus
  })
  const startIndex = (page - 1) * pageSize

  return {
    items: filteredItems.slice(startIndex, startIndex + pageSize),
    page,
    pageSize,
    totalCount: filteredItems.length,
    totalPages: Math.ceil(filteredItems.length / pageSize),
  }
}

export async function getSummary() {
  await delay(400)

  const totalFees = sampleRegistrations.reduce(
    (total, registration) => total + registration.registrationFee,
    0,
  )
  const totalPayments = sampleRegistrations.reduce(
    (total, registration) => total + registration.amountPaid,
    0,
  )

  return {
    totalRegistrations: sampleRegistrations.length,
    confirmed: sampleRegistrations.filter((registration) => registration.status === 'Confirmed').length,
    checkedIn: sampleRegistrations.filter((registration) => registration.status === 'CheckedIn').length,
    pending: sampleRegistrations.filter((registration) => registration.status === 'Pending').length,
    cancelled: sampleRegistrations.filter((registration) => registration.status === 'Cancelled').length,
    totalFees,
    totalPayments,
    uncollectedPayments: totalFees - totalPayments,
  }
}
